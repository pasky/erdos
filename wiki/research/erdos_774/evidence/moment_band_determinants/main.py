"""Check the 53 Smith-form covolumes of Walsh degree-band lattices.

The full domain is (d, ell) = (4, 2), (6, 3), (6, 4) and every nonempty set
J of degrees in {0, ..., ell}: 7 + 15 + 31 = 53 matrices. For each, the rows
are the Walsh characters (-1)^popcount(s AND x) whose degree popcount(s)
lies in J, in ascending mask order, and the columns are all 2^d points in
ascending mask order. The product of the Smith invariants is the index of
the row lattice in its saturation; the lattice generated by the rows has
covolume 2^(d rank / 2), so subtracting the binary valuation of the index
gives the exact saturated logarithmic covolume. The checks are that every
Smith invariant is a power of two, that the recorded multiplicities and
normalized covolumes in ``assets/moment_band_determinants.json`` are
reproduced, that the full-band values are 6/11, 5/7 and 5/19, and that no
proper degree union has smaller normalized covolume than its full band.
Arithmetic is exact integer Smith reduction; no search runs.

Run from the repository root:
    uv run --no-sync python wiki/research/erdos_774/evidence/moment_band_determinants/main.py

Dependencies are the standard library and the installed root ``tools``
package. The only input is the asset beside this script; no output file is
written and there is no reduced mode. Expected runtime is a few seconds.
Failed obligations exit nonzero, including under ``python -O``. This finite
diagnostic proves no general semistability statement; the compression
theorem on the owning lemma page does.
"""

from __future__ import annotations

import json
import pathlib
import sys
from fractions import Fraction

import tools

__all__ = [
    'smith_invariants',
    'main',
]

# locate the retained record relative to this script
_ASSET = pathlib.Path(__file__).with_name('assets') / 'moment_band_determinants.json'

# fix the pairs and the expected full-band normalized covolumes
_PAIRS = [(4, 2), (6, 3), (6, 4)]
_FULL = {(4, 2): Fraction(6, 11), (6, 3): Fraction(5, 7), (6, 4): Fraction(5, 19)}


def smith_invariants(rows: list[list[int]]) -> list[int]:
    """Return the nonzero Smith invariants of an integer matrix, as absolute values."""
    a = [row[:] for row in rows]
    m = len(a)
    n = len(a[0]) if a else 0
    invariants: list[int] = []
    t = 0
    while t < m and t < n:
        # choose a nonzero entry of least magnitude as the pivot
        pivot = None
        for i in range(t, m):
            for j in range(t, n):
                if a[i][j] and (pivot is None or abs(a[i][j]) < abs(a[pivot[0]][pivot[1]])):
                    pivot = (i, j)
        if pivot is None:
            break
        i, j = pivot
        a[t], a[i] = a[i], a[t]
        for row in a:
            row[t], row[j] = row[j], row[t]
        while True:
            p = a[t][t]
            restart = False
            # reduce the pivot column, swapping in any smaller remainder
            for i in range(t + 1, m):
                if a[i][t]:
                    q = a[i][t] // p
                    if q:
                        a[i] = [x - q * y for x, y in zip(a[i], a[t])]
                    if a[i][t]:
                        a[t], a[i] = a[i], a[t]
                        restart = True
                        break
            if restart:
                continue
            # reduce the pivot row, swapping in any smaller remainder
            for j in range(t + 1, n):
                if a[t][j]:
                    q = a[t][j] // p
                    if q:
                        for row in a:
                            row[j] -= q * row[t]
                    if a[t][j]:
                        for row in a:
                            row[t], row[j] = row[j], row[t]
                        restart = True
                        break
            if restart:
                continue
            # force the pivot to divide the remaining block
            bad = next((i for i in range(t + 1, m) for j in range(t + 1, n) if a[i][j] % p), None)
            if bad is not None:
                a[t] = [x + y for x, y in zip(a[t], a[bad])]
                continue
            break
        invariants.append(abs(a[t][t]))
        t += 1
    return invariants


def main() -> int:
    """Run every finite obligation and return the shared checker's exit code."""
    # parse the fixed-domain interface and load the retained record
    parser = tools.evidence_parser('Check the 53 Walsh degree-band Smith forms.', quick=False)
    parser.parse_args()
    checker = tools.Checker()
    recorded = {(block['d'], block['ell']): block for block in json.loads(_ASSET.read_text())['results']}
    checker.check('the record covers exactly the three pairs', set(recorded) == set(_PAIRS))
    total = 0
    for d, ell in _PAIRS:
        block = recorded[(d, ell)]
        cases = {tuple(case['degrees']): case for case in block['cases']}
        fresh = []
        power_failures = record_failures = 0
        for degree_mask in range(1, 1 << (ell + 1)):
            degrees = tuple(s for s in range(ell + 1) if degree_mask >> s & 1)
            rows = [s for s in range(1 << d) if s.bit_count() in degrees]
            matrix = [[(-1) ** ((s & x).bit_count()) for x in range(1 << d)] for s in rows]
            entries = smith_invariants(matrix)
            if len(entries) != len(rows) or not all(v > 0 and v & (v - 1) == 0 for v in entries):
                power_failures += 1
                continue
            index_exponent = sum(v.bit_length() - 1 for v in entries)
            exponent = Fraction(d * len(rows), 2) - index_exponent
            normalized = exponent / len(rows)
            multiplicities = {str(v): entries.count(v) for v in sorted(set(entries))}
            case = cases.get(degrees)
            if (
                case is None
                or case['rank'] != len(rows)
                or case['smith_multiplicities'] != multiplicities
                or Fraction(case['normalized_log2_covolume']) != normalized
            ):
                record_failures += 1
            fresh.append((degrees, normalized))
            total += 1
        label = f'(d, ell) = ({d}, {ell})'
        checker.check(f'{label}: {(1 << (ell + 1)) - 1} cases with full rank and power-of-two invariants', power_failures == 0 and len(fresh) == (1 << (ell + 1)) - 1)
        checker.check(f'{label}: recorded multiplicities and covolumes reproduced', record_failures == 0 and len(cases) == len(fresh), f'{record_failures} mismatches')
        full = dict(fresh)[tuple(range(ell + 1))]
        checker.check(f'{label}: full-band normalized covolume is {_FULL[(d, ell)]}', full == _FULL[(d, ell)] == Fraction(block['full_normalized_log2_covolume']), f'observed {full}')
        violations = [degrees for degrees, value in fresh if value < full]
        checker.check(f'{label}: no degree union has smaller normalized covolume', not violations and block['violations'] == [], f'violations {violations}')
    checker.check('53 matrices in total', total == 53, f'observed {total}')
    print(f'{total} Smith forms recomputed; no sublattice violation')
    return checker.finish()


if __name__ == '__main__':
    sys.exit(main())
