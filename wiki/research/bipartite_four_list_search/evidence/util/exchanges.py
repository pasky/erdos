"""Exact local exchanges of the 40-list construction on its twelve colours.

Deletion orbits are generated by explicitly checked colour permutations that
preserve the signed base family. For each orbit representative, all newly
uncovered palette subsets must be covered by the added signed four-subsets.
The recursion branches on every possible list covering one uncovered subset;
it is complete, and uses Python integer bitsets only. A time limit raises an
exception, never an exclusion result. No search logs or saved verdicts are read.
"""

from __future__ import annotations

import itertools
import math
import time
from collections.abc import Iterator

__all__ = ['ExchangeSearch', 'deletion_orbits']


def bits(s: int) -> Iterator[int]:
    """Enumerate the set-bit positions of a nonnegative integer."""
    while s:
        bit = s & -s
        yield bit.bit_length() - 1
        s -= bit


def generators(base: list[tuple[int, int]]) -> list[list[int]]:
    """Return nine checked colour-permutation actions on the 40 signed lists.

    They permute the four pairs, flip an even number of pairs, and preserve
    the two left 2-lists on the last four colours. Checking the actual signed
    lists is sufficient; knowing the order of the generated group is not used.
    """
    lookup = {signed: i for i, signed in enumerate(base)}
    swaps = [[(2 * i, 2 * i + 2), (2 * i + 1, 2 * i + 3)] for i in range(3)]
    swaps += [[(0, 1), (2 * i, 2 * i + 1)] for i in range(1, 4)]
    swaps += [[(8, 9)], [(10, 11)], [(8, 10), (9, 11)]]
    result = []
    for exchanges in swaps:
        perm = list(range(12))
        for x, y in exchanges:
            perm[x], perm[y] = perm[y], perm[x]
        action = [lookup[(side, sum(1 << perm[c] for c in bits(x)))] for side, x in base]
        if sorted(action) != list(range(40)):
            raise ValueError('colour permutation does not preserve the signed base')
        result.append(action)
    return result


def deletion_orbits(base: list[tuple[int, int]], r: int, deadline: float) -> tuple[list[int], int]:
    """Enumerate all r-subsets of the base and retain one per generated orbit."""
    actions = generators(base)
    seen: set[int] = set()
    reps = []
    for cs in itertools.combinations(range(40), r):
        if time.monotonic() >= deadline:
            raise TimeoutError('deletion orbit enumeration incomplete')
        s = sum(1 << c for c in cs)
        if s in seen:
            continue
        reps.append(s)
        todo = [s]
        seen.add(s)
        while todo:
            t = todo.pop()
            for action in actions:
                u = sum(1 << action[c] for c in bits(t))
                if u not in seen:
                    seen.add(u)
                    todo.append(u)
    if len(seen) != math.comb(40, r):
        raise ValueError('incomplete deletion coverage')
    return reps, len(seen)


class ExchangeSearch:
    """Exact covering oracle for added signed four-subsets of twelve colours."""

    def __init__(self, base: list[tuple[int, int]], seconds: float = 600) -> None:
        """Build event bitsets directly and validate the base domain."""
        if len(base) != 40 or len(set(base)) != 40:
            raise ValueError('need 40 distinct signed base lists')
        if any(side not in (0, 1) or x < 0 or x >= 4096 or x.bit_count() != 4 for side, x in base):
            raise ValueError('base lists must be signed four-subsets of twelve colours')
        self.base = base
        self.deadline = time.monotonic() + seconds
        self.nodes = 0
        self.signed = [(s, sum(1 << c for c in cs)) for s in (0, 1) for cs in itertools.combinations(range(12), 4)]
        self.coverage = []
        self.coverers: list[list[int]] = [[] for _ in range(4096)]
        for i, (side, x) in enumerate(self.signed):
            free = 4095 ^ x
            t = free
            covered = 0
            while True:
                point = (x | t) if side else t
                covered |= 1 << point
                self.coverers[point].append(i)
                if not t:
                    break
                t = (t - 1) & free
            self.coverage.append(covered)
        self.coverer_masks = [sum(1 << i for i in ids) for ids in self.coverers]
        self.tiers = [sum(1 << t for t in range(4096) if len(self.coverers[t]) == v) for v in sorted(set(map(len, self.coverers)))]
        self.groups: dict[int, int] = {}
        for t in range(4096):
            sig = sum(1 << i for i, (s, x) in enumerate(base) if ((x & t) == x if s else (x & t) == 0))
            if not sig:
                raise ValueError('base assignment is colourable')
            self.groups[sig] = self.groups.get(sig, 0) | (1 << t)

    def uncovered(self, deleted: int) -> int:
        """Return the palette subsets uncovered after deleting these base lists."""
        u = 0
        for sig, points in self.groups.items():
            if sig & ~deleted == 0:
                u |= points
        return u

    def pivot(self, u: int) -> int:
        """Choose an uncovered subset with as few possible covering lists as possible."""
        for tier in self.tiers:
            if u & tier:
                v = u & tier
                return (v & -v).bit_length() - 1
        raise ValueError('empty uncovered set')

    def repairs(self, u: int, k: int, memo: set[tuple[int, int]] | None = None) -> list[int] | None:
        """Return at most k candidate indices covering u, or None after exhaustion.

        At a node choose a subset T still uncovered. Any repair contains a
        candidate covering T, so branching over coverers[T] is complete.
        Identical residual sets and failed (k,u) states may be merged. At
        k=1 intersect the candidate sets covering each remaining subset.
        """
        self.nodes += 1
        if self.nodes % 1000 == 0 and time.monotonic() >= self.deadline:
            raise TimeoutError('repair search incomplete')
        if not u:
            return []
        if not k:
            return None
        if memo is None:
            memo = set()
        if (k, u) in memo:
            return None
        if k == 1:
            candidates = self.coverer_masks[self.pivot(u)]
            for point in bits(u):
                candidates &= self.coverer_masks[point]
                if not candidates:
                    return None
            return [(candidates & -candidates).bit_length() - 1]
        t = self.pivot(u)
        next_us = set()
        for i in self.coverers[t]:
            v = u & ~self.coverage[i]
            if v in next_us:
                continue
            next_us.add(v)
            rest = self.repairs(v, k - 1, memo)
            if rest is not None:
                return [i] + rest
        memo.add((k, u))
        return None
