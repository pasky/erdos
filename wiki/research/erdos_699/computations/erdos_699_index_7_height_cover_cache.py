#!/usr/bin/env python3
"""Checked, read-only memory-mapped cache for a shared prime/log prefix."""
from hashlib import sha256
import json
from pathlib import Path
import fcntl
import os

import numpy as np
from erdos_699_bft_prime_bootstrap import PrimeLogIntervals,SCALE,BUCKETS

ARRAY_KEYS={
    'primes':('prime_array_sha256',np.dtype('int64')),
    'prefix_lo':('lower_prefix_sha256',np.dtype('uint64')),
    'prefix_hi':('upper_prefix_sha256',np.dtype('uint64')),
    'log_lo':('log_table_lower_sha256',np.dtype('uint64')),
    'log_hi':('log_table_upper_sha256',np.dtype('uint64')),
}


def load_prime_prefix(directory,*,verify=True):
    directory=Path(directory)
    data=json.loads((directory/'metadata.json').read_text())
    metadata=data['prime_log_certificate']
    assert metadata['fixed_point_scale']==SCALE and metadata['logarithm_buckets']==BUCKETS
    theta=object.__new__(PrimeLogIntervals)
    theta.limit=metadata['sieve_limit']
    theta.metadata=metadata
    for name,(key,dtype)in ARRAY_KEYS.items():
        values=np.load(directory/(name+'.npy'),mmap_mode='r',allow_pickle=False)
        assert values.dtype==dtype and values.ndim==1
        if verify:assert sha256(memoryview(values)).hexdigest()==metadata[key],name
        values.flags.writeable=False
        setattr(theta,name,values)
    assert len(theta.primes)==metadata['prime_count']
    assert len(theta.prefix_lo)==len(theta.prefix_hi)==len(theta.primes)+1
    assert len(theta.log_lo)==len(theta.log_hi)==BUCKETS+1
    theta.log2_lo=int(theta.log_lo[-1]);theta.log2_hi=int(theta.log_hi[-1])
    return theta


def ensure_prime_prefix(limit=10**9,directory=None):
    directory=Path(directory or Path(__file__).resolve().parents[4]/'tmp'/'erdos699'/f'prime-prefix-{limit}')
    directory.mkdir(parents=True,exist_ok=True)
    with (directory/'build.lock').open('a+b')as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        if not (directory/'metadata.json').exists():
            theta=PrimeLogIntervals(limit)
            for name in ARRAY_KEYS:
                temporary=directory/(name+f'.{os.getpid()}.npy')
                np.save(temporary,getattr(theta,name),allow_pickle=False)
                temporary.replace(directory/(name+'.npy'))
            data={'prime_log_certificate':theta.metadata,
                  'construction':'Arrays generated by the retained PrimeLogIntervals; raw-array hashes are checked on load.'}
            temporary=directory/f'metadata.{os.getpid()}.json'
            temporary.write_text(json.dumps(data,indent=2)+'\n')
            temporary.replace(directory/'metadata.json')
            del theta
        result=load_prime_prefix(directory,verify=True)
        assert result.limit==limit
    return result,directory


if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--limit',type=int,default=10**9)
    parser.add_argument('--directory',type=Path)
    args=parser.parse_args()
    theta,directory=ensure_prime_prefix(args.limit,args.directory)
    print(json.dumps({'directory':str(directory),'metadata':theta.metadata},indent=2))
